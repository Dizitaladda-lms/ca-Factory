CREATE TABLE IF NOT EXISTS blog_authors (
  id BIGSERIAL PRIMARY KEY, name VARCHAR(255) NOT NULL, photo TEXT, bio TEXT,
  credentials TEXT, created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
