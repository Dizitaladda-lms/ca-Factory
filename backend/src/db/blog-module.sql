  blog_id INTEGER NOT NULL REFERENCES blogs(id) ON DELETE CASCADE,
  tag_id BIGINT NOT NULL REFERENCES blog_tags(id) ON DELETE CASCADE,
  PRIMARY KEY(blog_id, tag_id)
);
